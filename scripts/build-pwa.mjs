import {rename,readFile,writeFile,readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
await rename('dist/pwa/pwa.html','dist/pwa/index.html');
const base=process.env.ZAY_BASE_PATH||'/';
if(!/^\/(?:[A-Za-z0-9_-]+\/)*$/.test(base))throw Error('ZAY_BASE_PATH debe ser una ruta absoluta con barra final.');
const assets=(await readdir('dist/pwa/assets',{withFileTypes:true})).filter(x=>x.isFile()).map(x=>'assets/'+x.name).sort();
const paths=['','manifest.webmanifest','icons/icon-192.png','icons/icon-512.png','images/mochilas.png',...assets];
const precache=paths.map(p=>base+p);
const manifest=JSON.parse(await readFile('public/manifest.webmanifest','utf8'));
Object.assign(manifest,{id:base,start_url:base,scope:base});manifest.icons=manifest.icons.map(icon=>({...icon,src:base+icon.src.replace(/^\/+/,'')}));
await writeFile('dist/pwa/manifest.webmanifest',JSON.stringify(manifest));
const swSource=await readFile('public/sw.js','utf8');
const hash=createHash('sha256').update(swSource+base+JSON.stringify(manifest));
for(const p of paths)hash.update(await readFile('dist/pwa/'+(p||'index.html')));
const version=hash.digest('hex').slice(0,12);
const sw=swSource.replace("'zay-shell-v1'",JSON.stringify('zay-shell-'+version)).replace("const BASE='/';",'const BASE='+JSON.stringify(base)+';').replace(/const PRECACHE=\[[^;]*\];/,'const PRECACHE='+JSON.stringify(precache)+';');
await writeFile('dist/pwa/sw.js',sw);await writeFile('dist/pwa/.nojekyll','');
console.log(`PWA preparada en dist/pwa · base ${base} · ${precache.length} recursos sin conexión · ${version}`);
